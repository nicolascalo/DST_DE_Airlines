
DROP TABLE IF EXISTS Continent;
CREATE TABLE Continent (
Continent_ID serial PRIMARY KEY,
Continent_Name varchar(50) NOT NULL
);

DROP TABLE IF EXISTS Subcontinent;
CREATE TABLE Subcontinent (
Subcontinent_ID serial PRIMARY KEY,
Subcontinent_Name varchar(100) NOT NULL,
Continent_ID int DEFAULT NULL
);

DROP TABLE IF EXISTS Country;
CREATE TABLE Country (
Country_ID serial PRIMARY KEY,
Country_Name varchar(100) DEFAULT NULL,
Country_Code varchar(100) NOT NULL,
Subcontinent_ID int DEFAULT NULL
);

DROP TABLE IF EXISTS Location;
CREATE TABLE Location (
Location_ID serial PRIMARY KEY,
Location_name varchar(100) NOT NULL,
Country_ID int DEFAULT NULL
);

DROP TABLE IF EXISTS Airport;
CREATE TABLE Airport (
  Airport_ID serial PRIMARY KEY,
  Airport_Name varchar(100) NOT NULL,
  Iata_Code varchar(10) NOT NULL,
  Icao_Code varchar(10) NOT NULL,
  Latitude float NOT NULL,
  Longitude float NOT NULL,
  Location_ID int DEFAULT NULL
);

